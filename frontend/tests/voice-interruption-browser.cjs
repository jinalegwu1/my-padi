// Real recorded/Groq-generated speech in Chromium, with controlled AI replies
// for repeatable interruption stress checks and two real Whisper user turns.
const assert=require('node:assert/strict');
const {readFileSync,writeFileSync,existsSync,mkdirSync}=require('node:fs');
const {join}=require('node:path');
const {tmpdir}=require('node:os');
const {chromium}=require('playwright-core');

exports.verify=async(mode,sessionFile)=>{
  const session=JSON.parse(readFileSync(sessionFile,'utf8'));
  const frontend=process.env.PADI_VOICE_FRONTEND_URL||'http://localhost:8081';
  const api=process.env.PADI_VOICE_API_URL||'http://127.0.0.1:8080';
  const folder=join(tmpdir(),'my-padi-voice-interruptions');mkdirSync(folder,{recursive:true});
  const progress=stage=>writeFileSync(join(folder,'progress.json'),JSON.stringify({stage,at:Date.now()}));
  progress('creating input audio');
  const speech=async(text,name,style='chidi')=>{
    const file=join(folder,`${name}.wav`);
    if(existsSync(file))return readFileSync(file).toString('base64');
    const response=await fetch(`${api}/v1/voice/speak`,{method:'POST',headers:{Authorization:`Bearer ${session.token}`,'Content-Type':'application/json'},
      body:JSON.stringify({text,style,rate:1,language:'en-NG',groq_only:true}),signal:AbortSignal.timeout(65000)});
    assert.equal(response.status,200,'Public test speech must be generated by Groq.');
    const body=await response.json();writeFileSync(file,Buffer.from(body.audio_base64,'base64'));return body.audio_base64;
  };
  const stop=await speech('Stop.','stop');
  const question=await speech('Can you tell me what to cook tomorrow?','question');
  const first=await speech('I would like to plan','thought-start');
  const last=await speech('my dinner for tomorrow.','thought-end');
  const greeting=await speech('Hi, I’m listening.','greeting','ada');
  const previous=join(tmpdir(),'my-padi-playback-fixed');
  const timing=JSON.parse(readFileSync(join(previous,'timings.json'),'utf8'));
  const clips=timing.requests.map((request,i)=>({text:request.text.replace(/\s+/g,' ').trim(),audio:readFileSync(join(previous,`segment-${i+1}.wav`)).toString('base64')}));
  const reply=clips.map(clip=>clip.text).join(' ');
  const input=readFileSync(join(__dirname,'fixtures/please-continue.wav')).toString('base64');
  const browser=await chromium.launch({channel:'chrome',headless:true});
  let page;
  const expected=[],turns=[],transcripts=[],errors=[];
  const headers={'Access-Control-Allow-Origin':new URL(frontend).origin};
  try{
    const context=await browser.newContext({viewport:{width:430,height:900}});
    await context.addInitScript(({session})=>{
      sessionStorage.setItem('padi.auth.session.v1',JSON.stringify(session));
      localStorage.setItem('app:v1:chat-messages','[]');
      localStorage.setItem('app:v1:preferences',JSON.stringify({onboarded:true,voiceId:'ada',voiceRate:1,languageCode:'en-NG',
        countryCode:'NG',appearance:'light',displayName:'Voice interruption check',reduceMotion:true,notificationsEnabled:false,
        dailyCheckIn:false,checkInTime:'08:00',textScale:1,wakeWordEnabled:false,showVoiceTranscript:false}));
      const audit=window.__interrupt={clips:[],stops:[],input:null,users:[]};
      window.__padiEchoTrace=[];
      const Context=AudioContext;
      navigator.mediaDevices.getUserMedia=async constraints=>{
        const input=new Context({sampleRate:48000});await input.resume();
        const destination=input.createMediaStreamDestination();audit.input=input;audit.destination=destination;
        audit.constraints=constraints; audit.tracks=destination.stream.getTracks();
        audit.tracks.forEach(track=>{const stop=track.stop.bind(track);track.stop=()=>{stop();void input.close();};});
        return destination.stream;
      };
      const start=AudioBufferSourceNode.prototype.start,stop=AudioBufferSourceNode.prototype.stop,echoes=new WeakMap();
      AudioBufferSourceNode.prototype.start=function(when=0,...args){
        if(this.context===audit.input)return start.call(this,when,...args);
        audit.output=this.context;
        const at=Math.max(when,this.context.currentTime);
        const clip={calledAt:Date.now(),at:Date.now()+(at-this.context.currentTime)*1000,duration:this.buffer.duration,ended:false};
        audit.clips.push(clip);this.addEventListener('ended',()=>{clip.ended=true;});
        const result=start.call(this,when,...args);
        if(audit.input?.state==='running'){
          const echo=audit.input.createBufferSource(),gain=audit.input.createGain();
          echo.buffer=this.buffer;gain.gain.value=.35;echo.connect(gain);gain.connect(audit.destination);echoes.set(this,echo);
          start.call(echo,audit.input.currentTime+Math.max(0,at-this.context.currentTime));
        }
        return result;
      };
      AudioBufferSourceNode.prototype.stop=function(...args){
        if(this.context!==audit.input)audit.stops.push(Date.now());
        try{if(echoes.has(this))stop.call(echoes.get(this));}catch{}
        return stop.apply(this,args);
      };
      audit.say=async(encoded)=>{
        const buffer=await audit.input.decodeAudioData(Uint8Array.from(atob(encoded),c=>c.charCodeAt(0)).buffer);
        const samples=buffer.getChannelData(0),window=Math.round(buffer.sampleRate*.01);let voiced=0,last=0,found=false;
        for(let i=0;i<samples.length;i+=window){let power=0;for(let j=i;j<Math.min(i+window,samples.length);j++)power+=samples[j]*samples[j];
          if(Math.sqrt(power/window)>.004){if(!found){voiced=i/buffer.sampleRate;found=true;}last=Math.min(i+window,samples.length);}}
        const begin=Math.max(0,Math.floor(voiced*buffer.sampleRate)-Math.round(buffer.sampleRate*.05)),end=Math.min(samples.length,last+Math.round(buffer.sampleRate*.08));
        const speech=audit.input.createBuffer(1,end-begin,buffer.sampleRate);speech.getChannelData(0).set(samples.subarray(begin,end));
        voiced-=begin/buffer.sampleRate;
        const source=audit.input.createBufferSource();source.buffer=speech;source.connect(audit.destination);
        const at=Date.now();audit.userVoicedAt=at+voiced*1000;
        audit.users.push({at:performance.now(),duration:speech.duration});audit.userPlaying=true;
        await new Promise(resolve=>{source.onended=()=>{audit.userPlaying=false;resolve();};source.start();});
        return audit.userVoicedAt;
      };
    },{session});
    page=await context.newPage();page.setDefaultTimeout(30000);page.setDefaultNavigationTimeout(120000);
    page.on('pageerror',error=>errors.push(error.message));
    await page.route('**/v1/voice/speak',route=>{
      if(route.request().method()==='OPTIONS')return route.continue();
      const body=route.request().postDataJSON();assert.equal(body.groq_only,true,'Gemini speech must never be requested.');
      const key=body.text.replace(/\s+/g,' ').trim();
      const audio=key==='Hi, I’m listening.'?greeting:clips.find(clip=>clip.text===key)?.audio;
      if(!audio){errors.push(`Unexpected speech text: ${key}`);return route.abort();}
      return route.fulfill({status:200,contentType:'application/json',headers,body:JSON.stringify({audio_base64:audio,mime_type:'audio/wav'})});
    });
    await page.route('**/v1/chat',route=>{
      if(route.request().method()==='OPTIONS')return route.continue();
      const body=route.request().postDataJSON();assert.equal(body.delivery,'voice');assert.equal(body.stream,true);
      if(!body.greeting)turns.push(body);
      const words=body.greeting?'Hi, I’m listening.':reply;
      return route.fulfill({status:200,contentType:'text/event-stream',headers,
        body:`event: delta\ndata: ${JSON.stringify({text:words})}\n\nevent: done\ndata: ${JSON.stringify({reply:words,memory_revision:0})}\n\n`});
    });
    await page.route('**/v1/voice/transcribe*',route=>{
      if(route.request().method()==='OPTIONS')return route.continue();
      const payload=route.request().postDataBuffer(),offset=payload?.indexOf(Buffer.from('RIFF'))??-1;
      const capture=join(folder,`captured-${transcripts.length+1}.wav`);
      if(offset>=0&&offset+8<=payload.length){const end=offset+payload.readUInt32LE(offset+4)+8;if(end<=payload.length)writeFileSync(capture,payload.subarray(offset,end));}
      const next=expected.shift();
      if(!next){errors.push('Speaker audio created an unexpected user turn');return route.abort();}
      transcripts.push({at:Date.now(),real:!!next.real});
      if(next.real)return route.continue();
      return route.fulfill({status:200,contentType:'application/json',headers,body:JSON.stringify({text:next.text})});
    });
    const listening=()=>page.getByRole('button',{name:/portrait, PADI listening$/}).waitFor({timeout:70000});
    const speaking=async()=>{
      await page.getByRole('button',{name:/portrait, PADI speaking$/}).waitFor({timeout:30000});
      await page.waitForFunction(()=>__interrupt.clips.some(clip=>!clip.ended&&clip.at<=Date.now()),null,{timeout:30000});
    };
    const say=encoded=>page.evaluate(encoded=>__interrupt.say(encoded),encoded);
    const startTurn=async()=>{
      const before=await page.evaluate(()=>__interrupt.clips.length);
      expected.push({text:'Please repeat the cooking instructions.'});await say(input);
      await page.waitForFunction(count=>__interrupt.clips.slice(count).some(clip=>!clip.ended&&clip.at<=Date.now()),before,{timeout:30000});
      await speaking();
    };
    const interrupt=async(encoded,transcript)=>{
      const before=await page.evaluate(()=>({clips:__interrupt.clips.length,stops:__interrupt.stops.length}));
      expected.push(transcript);
      const played=say(encoded);
      await page.waitForFunction(count=>__interrupt.stops.length>count,before.stops);
      const interrupted=await page.evaluate(index=>({clips:__interrupt.clips.length,stoppedAt:__interrupt.stops[index]}),before.stops);
      await listening();const measured=await page.evaluate(({index})=>__interrupt.stops[index]-__interrupt.userVoicedAt,{index:before.stops});
      assert.ok(measured>=-40&&measured<500,`Speech onset should interrupt promptly (${measured} ms).`);
      await played;
      return {latencyMs:measured,oldClips:interrupted.clips,stoppedAt:interrupted.stoppedAt};
    };
    progress('opening voice mode');await page.goto(`${frontend}/voice`);
    await page.getByRole('button',{name:/portrait, PADI idle$/}).click();
    if(mode==='diagnostic'){
      await page.waitForFunction(()=>__interrupt.clips.length&&(__interrupt.stops.length||__interrupt.clips.every(clip=>clip.ended)),null,{timeout:10000});
      const diagnostic=await page.evaluate(()=>({clips:__interrupt.clips,stops:__interrupt.stops}));
      assert.equal(diagnostic.stops.length,0,'PADI cannot interrupt its own greeting');
      writeFileSync(join(folder,'echo-diagnostic.json'),JSON.stringify(diagnostic));console.log('Echo diagnostic saved.');return;
    }
    await listening();
    assert.equal(transcripts.length,0,'Greeting echo must not create a user turn');
    progress('Stop with real Whisper');await startTurn();
    const stopResponse=page.waitForResponse(response=>new URL(response.url()).pathname==='/v1/voice/transcribe');
    void stopResponse.catch(()=>{});
    const stopped=await interrupt(stop,mode==='echo-stress'?{text:'Stop.'}:{real:true});
    const result=await stopResponse;assert.equal(result.status(),200);
    const stoppedWords=(await result.json()).text;assert.match(stoppedWords,/stop/i);await listening();
    assert.equal(turns.length,1,'Stop cancels speech without another Groq reply');
    assert.equal(await page.evaluate(()=>__interrupt.clips.length),stopped.oldClips,'Cancelled audio did not restart');
    progress('new question with real Whisper');await startTurn();
    const questionResponse=page.waitForResponse(response=>new URL(response.url()).pathname==='/v1/voice/transcribe');
    void questionResponse.catch(()=>{});
    const questioned=await interrupt(question,{real:true});
    const answer=await questionResponse;assert.equal(answer.status(),200);
    const questionWords=(await answer.json()).text;assert.match(questionWords,/cook|tomorrow/i);await speaking();
    assert.match(turns.at(-1).messages.at(-1).content,/cook|tomorrow/i);
    assert.ok(turns.at(-1).messages.some(message=>message.role==='assistant'&&message.content===reply),'Context survives interruption');
    progress('brief pause within a thought');
    const count=transcripts.length;expected.push({text:'I would like to plan my dinner for tomorrow.'});
    const before=await page.evaluate(()=>__interrupt.stops.length);await say(first);
    await page.waitForFunction(count=>__interrupt.stops.length>count,before);
    await page.waitForTimeout(700);assert.equal(transcripts.length,count,'A brief pause cannot submit half a thought');
    await say(last);await speaking();
    assert.equal(transcripts.length,count+1);assert.equal(turns.at(-1).messages.at(-1).content,'I would like to plan my dinner for tomorrow.');
    progress('repeated interruptions');const repeated=[];
    for(let i=0;i<(['stress','echo-stress'].includes(mode)?15:3);i++){
      const interrupted=await interrupt(question,{text:`New question number ${i+1}?`});repeated.push(interrupted.latencyMs);await speaking();
    }
    progress('natural completion');await listening();
    assert.deepEqual(errors,[]);assert.equal(expected.length,0);
    const audit=await page.evaluate(()=>({clips:__interrupt.clips,stops:__interrupt.stops,constraints:__interrupt.constraints}));
    assert.equal(audit.constraints.audio.echoCancellation,true);
    const report={stopLatencyMs:stopped.latencyMs,questionLatencyMs:questioned.latencyMs,repeatedLatencyMs:repeated,
      stoppedWords,questionWords,turns:turns.length,transcriptions:transcripts.length,actualAudio:true,stopUsesWhisper:mode!=='echo-stress',
      scenarios:['Stop','new question','double talk','brief pause','complete thought response','repeated interruption','natural completion']};
    writeFileSync(join(folder,'verification.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report));
    await page.getByRole('button',{name:'Switch to text',exact:true}).click();
    await page.waitForFunction(()=>__interrupt.tracks.every(track=>track.readyState==='ended'));
    console.log(`PASS: all seven interruption/turn scenarios used real audio; ${mode==='echo-stress'?'the new question used Faster-Whisper (Stop response was controlled to isolate echo)':'Stop and the new question were transcribed by Faster-Whisper'}.`);
  }catch(error){progress(`failed: ${error.message}`);console.error(error.message);console.error({errors,transcripts,turns:turns.length});if(page){
    const diagnostic=await page.evaluate(()=>({alerts:[...document.querySelectorAll('[role="alert"]')].map(e=>e.textContent),audit:__interrupt.clips,stops:__interrupt.stops,echo:window.__padiEchoTrace,users:__interrupt.users})).catch(()=>({}));
    writeFileSync(join(folder,'failure.json'),JSON.stringify(diagnostic,null,2));console.error({clips:diagnostic.audit,stops:diagnostic.stops});
  }throw error;}
  finally{await browser.close();}
};
